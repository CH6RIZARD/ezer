// Port of apps/mobile/components/CameraDove.tsx
//
// The one loader: a dove that comes out of the phone's camera. There are no spinners. A wait
// registers with
//   someView.cameraDove(isBusy)            // RN useCameraDove(active, label?)
//   DoveLoader(active: isBusy)             // RN <DoveLoader active /> (draws nothing where placed)
// and ONE host, its own pass-through window (OverlayWindows, below the lock, above presented
// sheets: RN's FullWindowOverlay), flies a rendered dove out of the camera, keeps it hovering in the
// ~21 pt band between the camera and the header while any registration is active, and when the
// last ends finishes the current lap and flies FULLY back into the camera. Rules (owner, Oct 2026):
//   - each appearance picks one of the approved paths A, B, C, F at random, never twice in a row;
//   - it only comes out if the wait outlasts WAIT_MS; once out it always completes in and out;
//   - only the exit goes into the camera, all the way (no sliver at the island's edge);
//   - Reduce Motion: a still dove fades in and out near the camera point;
//   - backgrounded or behind the lock: gone at once, back after the wait if still loading.
// Frame data: CameraDoveFrames.swift; sheets: Resources/dove/dove-camera-*.webp (both generated by
// E:\ezer-dove\loaders\work\export_app_doves.py). Camera point: top-centre, half the top inset down.

import SwiftUI
import UIKit

private let WAIT_MS: Double = 300
private let FPS: Double = 30
/// Reduce Motion: frames of fade in and out around the still dove.
private let RM_FADE: Double = 8

/// WebP sprite sheets in Bundle.module (UIImage(named:) only finds PNG/JPEG; ImageIO decodes WebP).
@MainActor
enum DoveSheets {
    private static var cache: [String: UIImage] = [:]
    private static var decoded: Set<String> = []

    static func image(_ name: String) -> UIImage? {
        if let i = cache[name] { return i }
        let i = Bundle.module.url(forResource: name, withExtension: "webp").flatMap { UIImage(contentsOfFile: $0.path) }
        cache[name] = i
        return i
    }

    /// Decodes off the main thread and keeps the decoded copy. False when the file is missing.
    @discardableResult
    static func prepare(_ name: String) async -> Bool {
        if decoded.contains(name) { return true }
        guard let img = image(name) else { return false }
        cache[name] = await img.byPreparingForDisplay() ?? img
        decoded.insert(name)
        return true
    }
}

@Observable
@MainActor
final class CameraDoveCenter {
    static let shared = CameraDoveCenter()
    struct Run: Equatable {
        let path: Int
        let serial: Int
    }

    private(set) var run: Run?
    @ObservationIgnored private var regs: [(token: Int, label: String)] = []
    @ObservationIgnored private var nextToken = 0
    @ObservationIgnored private var lockOpen = false
    @ObservationIgnored private var active = true
    @ObservationIgnored private var timer: Task<Void, Never>?
    @ObservationIgnored private var last: Int?
    @ObservationIgnored private var serial = 0
    // The clock, advanced by the view's TimelineView. phase: 0 in, 1 loop, 2 out, 3 done.
    @ObservationIgnored private var phase = 3
    @ObservationIgnored private var t: Double = 0
    @ObservationIgnored private var lastTick: Date?

    private var gate: Bool { lockOpen && active }
    private var want: Bool { !regs.isEmpty && gate }

    private init() {
        let nc = NotificationCenter.default
        nc.addObserver(forName: UIApplication.willResignActiveNotification, object: nil, queue: .main) { [weak self] _ in
            MainActor.assumeIsolated { self?.active = false; self?.update() }
        }
        nc.addObserver(forName: UIApplication.didBecomeActiveNotification, object: nil, queue: .main) { [weak self] _ in
            MainActor.assumeIsolated { self?.active = true; self?.update() }
        }
    }

    func register(_ label: String) -> Int {
        nextToken += 1
        regs.append((nextToken, label))
        update()
        return nextToken
    }

    func unregister(_ token: Int) {
        regs.removeAll { $0.token == token }
        update()
    }

    /// LockGateModel reports the lock (RN LockOpenContext).
    func setLockOpen(_ open: Bool) {
        guard open != lockOpen else { return }
        lockOpen = open
        update()
    }

    private func update() {
        if !gate {
            timer?.cancel()
            timer = nil
            if run != nil { stop() }
            return
        }
        if run != nil { return } // the clock reads `want`: loops on, or finishes the lap and goes in
        if want && timer == nil {
            timer = Task { [weak self] in
                try? await Task.sleep(nanoseconds: UInt64(WAIT_MS * 1_000_000))
                guard let self, !Task.isCancelled else { return }
                self.timer = nil
                if self.want && self.run == nil { self.start() }
            }
        } else if !want, let tm = timer {
            tm.cancel()
            timer = nil
        }
    }

    private func start() {
        let n = CameraDoveFrames.paths.count
        let pool = (0..<n).filter { $0 != last }
        let p = pool.randomElement() ?? 0
        last = p
        serial += 1
        phase = 0
        t = 0
        lastTick = nil
        run = Run(path: p, serial: serial)
        OverlayWindows.shared.setCameraDoveVisible(true)
        if let label = regs.last?.label { UIAccessibility.post(notification: .announcement, argument: label) }
    }

    private func stop() {
        run = nil
        phase = 3
        OverlayWindows.shared.setCameraDoveVisible(false)
    }

    private func done(_ s: Int) {
        guard let r = run, r.serial == s else { return }
        stop()
        update() // still loading: it comes out again (after the wait)
    }

    /// Advances the clock to `now` (RN: the UI-thread frame callback) and returns the frame to draw:
    /// the index into the path's in + loop + out frames, and the opacity.
    func tick(_ now: Date, path P: CameraDovePath, reduced: Bool) -> (i: Int, o: Double) {
        let NI = reduced ? RM_FADE : Double(P.ni)
        let NL = reduced ? 1 : Double(P.nl)
        let NO = reduced ? RM_FADE : Double(P.no)
        if phase != 3 {
            // Capped: after a long stall it skips at most a few frames, never a whole clip.
            let dt = lastTick.map { min(0.1, max(0, now.timeIntervalSince($0))) } ?? 0
            lastTick = now
            var x = t + dt * FPS
            if phase == 0 && x >= NI { phase = 1; x -= NI }
            if phase == 1 && x >= NL {
                x -= NL
                if !want { phase = 2 }
            }
            if phase == 2 && x >= NO {
                phase = 3
                x = NO - 0.001
                if let s = run?.serial { DispatchQueue.main.async { self.done(s) } }
            }
            t = x
        }
        if reduced {
            let o = phase == 0 ? t / RM_FADE : phase == 1 ? 1 : phase == 2 ? 1 - t / RM_FADE : 0
            return (P.ni, o) // loop frame 0, under the camera
        }
        let k = Int(t)
        let i = phase == 0 ? min(k, P.ni - 1) : phase == 1 ? P.ni + k % P.nl : P.ni + P.nl + min(k, P.no - 1)
        return (i, phase == 3 ? 0 : P.f[i * 4 + 3])
    }
}

/// The camera dove window's root (OverlayWindows).
struct CameraDoveRoot: View {
    @Environment(ThemeStore.self) private var theme

    var body: some View {
        RNRoot {
            CameraDoveView()
        }
        .ignoresSafeArea()
        .allowsHitTesting(false)
    }
}

private struct CameraDoveView: View {
    @Environment(ThemeStore.self) private var theme
    @Environment(\.safeInsets) private var insets
    @Environment(\.windowSize) private var win
    @Environment(\.accessibilityReduceMotion) private var reduced
    private var center: CameraDoveCenter { CameraDoveCenter.shared }

    var body: some View {
        ZStack(alignment: .topLeading) {
            if let run = center.run {
                let P = CameraDoveFrames.paths[run.path]
                // Camera point and path.json's fit rule (band = content top - camera y).
                let bar = Double(insets.top)
                let fp = min(1, max(CameraDoveFrames.posMin, (bar + 10 - bar / 2) / CameraDoveFrames.bandRef))
                let fs = 0.4 + 0.6 * fp
                let sd = Double(win.width) / 390 * fp
                TimelineView(.animation) { tl in
                    let q = center.tick(tl.date, path: P, reduced: reduced)
                    SpriteCell(image: DoveSheets.image(P.sheet), cellW: P.cell, cellH: P.cell, cols: P.cols, rows: P.rows,
                               i: q.i, edge: EdgeReader.edge(theme))
                        .scaleEffect(P.f[q.i * 4 + 2] * fs)
                        .opacity(q.o)
                        .position(x: Double(win.width) / 2 + P.f[q.i * 4] * sd, y: bar / 2 + P.f[q.i * 4 + 1] * sd)
                }
                .id(run.serial)
            }
        }
        .frame(maxWidth: .infinity, maxHeight: .infinity, alignment: .topLeading)
    }
}

private struct CameraDoveModifier: ViewModifier {
    let active: Bool
    let label: String
    @State private var token: Int?

    func body(content: Content) -> some View {
        content
            .onChange(of: active, initial: true) { _, a in sync(a) }
            .onAppear { sync(active) }
            .onDisappear { sync(false) }
    }

    private func sync(_ on: Bool) {
        if on, token == nil {
            token = CameraDoveCenter.shared.register(label)
        } else if !on, let t = token {
            CameraDoveCenter.shared.unregister(t)
            token = nil
        }
    }
}

extension View {
    /// Shows the camera dove while `active` (after ~300 ms). `label` is announced to VoiceOver.
    func cameraDove(_ active: Bool, label: String = "Loading") -> some View {
        modifier(CameraDoveModifier(active: active, label: label))
    }
}

/// RN <DoveLoader active />: registers a wait, draws nothing.
struct DoveLoader: View {
    var active = true
    var label = "Loading"

    var body: some View {
        Color.clear.frame(width: 0, height: 0).cameraDove(active, label: label)
    }
}
